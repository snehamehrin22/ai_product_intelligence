"""Pydantic schemas for request/response validation.

Single source of truth for all data structures in the API.
"""

from pydantic import BaseModel, Field
from typing import Optional
from datetime import datetime
from enum import Enum


class TaskStatus(str, Enum):
    """Task status enumeration."""

    PENDING = "pending"
    IN_PROGRESS = "in_progress"
    COMPLETED = "completed"
    CANCELLED = "cancelled"


class TaskPriority(str, Enum):
    """Task priority enumeration."""

    LOW = "low"
    MEDIUM = "medium"
    HIGH = "high"
    URGENT = "urgent"


class TaskCreate(BaseModel):
    """Schema for creating a new task.

    Note: task_id, created_at, updated_at are auto-generated by the backend.
    """

    user_id: str = Field(..., min_length=1, max_length=100, description="User ID who owns the task")
    title: str = Field(..., min_length=1, max_length=200, description="Task title")
    description: Optional[str] = Field(None, max_length=2000, description="Detailed task description")
    status: TaskStatus = Field(default=TaskStatus.PENDING, description="Task status")
    priority: TaskPriority = Field(default=TaskPriority.MEDIUM, description="Task priority")
    due_date: Optional[datetime] = Field(None, description="Optional due date/time")

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "user_id": "test-user-001",
                    "title": "Buy groceries",
                    "description": "Milk, eggs, bread",
                    "status": "pending",
                    "priority": "medium",
                    "due_date": "2026-07-08T18:00:00"
                }
            ]
        }
    }


class TaskUpdate(BaseModel):
    """Schema for updating an existing task.

    All fields are optional except task_id (provided in path).
    Only provided fields will be updated.
    """

    title: Optional[str] = Field(None, min_length=1, max_length=200, description="Task title")
    description: Optional[str] = Field(None, max_length=2000, description="Task description")
    status: Optional[TaskStatus] = Field(None, description="Task status")
    priority: Optional[TaskPriority] = Field(None, description="Task priority")
    due_date: Optional[datetime] = Field(None, description="Due date/time")

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "status": "completed"
                },
                {
                    "title": "Buy groceries and cook dinner",
                    "priority": "high",
                    "due_date": "2026-07-07T18:00:00"
                }
            ]
        }
    }


class TaskResponse(BaseModel):
    """Schema for task responses from the API.

    Includes all fields including auto-generated ones.
    """

    task_id: str = Field(..., description="Unique task identifier")
    user_id: str = Field(..., description="User ID who owns the task")
    title: str = Field(..., description="Task title")
    description: Optional[str] = Field(None, description="Task description")
    status: TaskStatus = Field(..., description="Task status")
    priority: TaskPriority = Field(..., description="Task priority")
    due_date: Optional[datetime] = Field(None, description="Due date/time")
    created_at: datetime = Field(..., description="Task creation timestamp")
    updated_at: datetime = Field(..., description="Last update timestamp")

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "task_id": "task-001",
                    "user_id": "test-user-001",
                    "title": "Buy groceries",
                    "description": "Milk, eggs, bread",
                    "status": "pending",
                    "priority": "medium",
                    "due_date": "2026-07-08T18:00:00",
                    "created_at": "2026-07-06T10:00:00",
                    "updated_at": "2026-07-06T10:00:00"
                }
            ]
        }
    }


class TaskListResponse(BaseModel):
    """Schema for paginated task list responses."""

    tasks: list[TaskResponse] = Field(..., description="List of tasks")
    total: int = Field(..., description="Total number of tasks")

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "tasks": [
                        {
                            "task_id": "task-001",
                            "user_id": "test-user-001",
                            "title": "Buy groceries",
                            "description": "Milk, eggs, bread",
                            "status": "pending",
                            "priority": "medium",
                            "due_date": None,
                            "created_at": "2026-07-06T10:00:00",
                            "updated_at": "2026-07-06T10:00:00"
                        }
                    ],
                    "total": 1
                }
            ]
        }
    }


class ErrorResponse(BaseModel):
    """Schema for error responses."""

    detail: str = Field(..., description="Error message")
    error_type: Optional[str] = Field(None, description="Error type/code")

    model_config = {
        "json_schema_extra": {
            "examples": [
                {
                    "detail": "Task not found",
                    "error_type": "NOT_FOUND"
                }
            ]
        }
    }
